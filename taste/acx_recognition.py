"""Contamination / provenance check for the ACX images: does the rater recognise the work, and does it think it is AI?
Then: is its preference for human art still there on images it did NOT identify?

  python -m taste.acx_recognition claude-opus-5.5 qwen3.5-397b-a17b
"""
import json, re, sys
from concurrent.futures import ThreadPoolExecutor
import pandas as pd
from tqdm.auto import tqdm
from taste.paths import DATA
from taste.models import BY_NAME
from taste.rate_api import content
from taste.gen_haiku import openrouter, REASONING

Q = ("Do you recognise this specific image? If it is a known work, name the artist and title; otherwise say unknown. "
     "Also say whether you think it was made by a human artist or generated by an AI. "
     'Reply with JSON only: {"artist": "<name or unknown>", "title": "<title or unknown>", "origin": "human" or "ai"}')


def surname_hit(guess, explanation):
    """the rater named the right artist: any capitalised word (>3 letters) of its artist guess appears in Scott's answer text."""
    words = [w for w in re.findall(r"[A-Z][a-zA-Z\-']{3,}", guess or "")]
    return any(w in explanation for w in words)


def main(names):
    it = pd.read_parquet(DATA / "images_items.parquet").set_index("item_id")
    acx = it[it.dataset == "acx"].join(pd.read_parquet(DATA / "acx_images.parquet").assign(item_id=lambda d: [f"acx_{i:02d}" for i in d.acx_idx]).set_index("item_id")[["explanation"]])
    client = openrouter()
    for name in names:
        mid = BY_NAME[name].api

        def call(row):
            c = content("images", row); c[-1] = {"type": "text", "text": Q}
            r = client.chat.completions.create(model=mid, messages=[{"role": "user", "content": c}], temperature=0.0, max_tokens=2000,
                                               extra_body={"reasoning": REASONING.get(mid, {"enabled": False}), "usage": {"include": True}})
            txt = r.choices[0].message.content
            d = json.loads(txt[txt.index("{"): txt.rindex("}") + 1])
            return dict(item_id=row.Index, artist=d["artist"], title_guess=d["title"], origin=d["origin"].lower(), cost=r.usage.model_extra.get("cost", 0.0))
        with ThreadPoolExecutor(8) as ex: rows = list(tqdm(ex.map(call, acx.itertuples()), total=len(acx), desc=name))
        df = pd.DataFrame(rows).set_index("item_id").join(acx[["source", "title", "explanation"]])
        df["identified"] = [(s == "human") and surname_hit(a, e) for a, s, e in zip(df.artist, df.source, df.explanation)]
        df["origin_correct"] = df.origin == df.source
        df.to_parquet(DATA / f"acx_recognition_{name}.parquet")
        print(f"{name}: ${df.cost.sum():.2f} | identified {df.identified.sum()}/{(df.source == 'human').sum()} human works | origin accuracy {df.origin_correct.mean():.2f}")
        print(df[df.identified][["title", "artist", "title_guess"]].to_string())


if __name__ == "__main__":
    main(sys.argv[1:])
