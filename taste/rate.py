"""Forward-pass rater (no sampling): rating = expected digit under the next-token distribution (Q-Align style readout),
plus hidden states in the same pass.

  python -m taste.rate <rater> haiku|images [--check]

ratings/<set>/<rater>.parquet: item_id, score = E[k | k in 1..9], p1..p9, digit_mass,
    haiku: logprob_mean (rater's mean log p of the haiku tokens in context = familiarity/perplexity confound), n_item_tokens
    images: p_human (P('Human') vs P('AI') to the origin question)
hidden/<set>/<rater>.npz: item_id, layers, last [N,L,d] (final prompt token, where the rating is read out),
    mean [N,L,d] (mean over the item's own tokens: haiku tokens / image tokens), float16
"""
import argparse, gc
import numpy as np
import pandas as pd
import torch
from PIL import Image
from tqdm.auto import tqdm
from transformers import AutoProcessor, AutoModelForImageTextToText
from taste.paths import DATA, RATINGS, HIDDEN
from taste.models import BY_NAME

SCALE = "Rate it from 1 to 9, where 1 = very poor, 5 = average and 9 = masterpiece. Reply with a single digit."
HAIKU_Q = "Here is a haiku:\n\n{haiku}\n\nHow good is this haiku as a poem? " + SCALE
IMAGE_Q = "How good is this image, aesthetically? " + SCALE
ORIGIN_Q = "Was this image made by a human artist or generated by an AI? Reply with one word: Human or AI."
N_LAYERS_KEPT = 13


class Rater:
    def __init__(self, name):
        hf = BY_NAME[name].hf
        self.proc = AutoProcessor.from_pretrained(hf, use_fast=False)  # PIL backend: torchvision was 10-25x slower per image here
        self.tok = self.proc.tokenizer
        self.tok.padding_side = "left"
        # spread over the visible GPUs (6 GiB headroom each for activations); 35B-A3B is ~70 GB in bf16 and spills onto the CPU on one H100
        gpus = {i: f"{torch.cuda.get_device_properties(i).total_memory // 2**30 - 6}GiB" for i in range(torch.cuda.device_count())}
        self.model = AutoModelForImageTextToText.from_pretrained(hf, dtype=torch.bfloat16, device_map="auto", max_memory={**gpus, "cpu": "400GiB"}).eval()
        self.batch = 1  # one item per forward: even unpadded equal-length batches shifted scores by up to 0.09 (batch-shape-dependent numerics)
        self.digits = [self.first_id(str(d), single=True) for d in range(1, 10)]
        self.origin = [self.first_id(w) for w in ("Human", "AI")]
        assert self.origin[0] != self.origin[1]
        n = self.model.config.get_text_config().num_hidden_layers
        self.layers = sorted(set(np.linspace(0, n, N_LAYERS_KEPT).round().astype(int).tolist()))
        self.image_token_id = self.tok.convert_tokens_to_ids(self.proc.image_token)

    def first_id(self, s, single=False):
        ids = self.tok.encode(s, add_special_tokens=False)
        assert not single or len(ids) == 1, (s, ids)
        return ids[0]

    def render(self, content):
        return self.proc.apply_chat_template([{"role": "user", "content": content}], tokenize=False, add_generation_prompt=True, enable_thinking=False)

    def encode_haiku(self, haikus):
        texts = [self.render([{"type": "text", "text": HAIKU_Q.format(haiku=h)}]) for h in haikus]
        encs = [self.tok(t, add_special_tokens=False, return_offsets_mapping=True) for t in texts]
        T = max(len(e.input_ids) for e in encs)
        ids = torch.full((len(texts), T), self.tok.pad_token_id); att = torch.zeros_like(ids); span = torch.zeros_like(ids, dtype=torch.bool)
        for i, (t, e, h) in enumerate(zip(texts, encs, haikus)):
            a = t.index(h); b = a + len(h); off = T - len(e.input_ids)
            ids[i, off:] = torch.tensor(e.input_ids); att[i, off:] = 1
            span[i, off:] = torch.tensor([o[0] < b and o[1] > a for o in e.offset_mapping])
        return dict(input_ids=ids, attention_mask=att), span, texts

    def encode_images(self, paths, prompt):
        imgs = [Image.open(DATA / p).convert("RGB") for p in paths]
        texts = [self.render([{"type": "image"}, {"type": "text", "text": prompt}]) for _ in imgs]
        enc = self.proc(text=texts, images=[[im] for im in imgs], return_tensors="pt", padding=True, add_special_tokens=False)
        return dict(enc), enc["input_ids"] == self.image_token_id, texts

    @torch.no_grad()
    def forward(self, enc, span, hidden=True, familiarity=False):
        enc = {k: v.to(self.model.device) for k, v in enc.items()}
        out = self.model(**enc, output_hidden_states=hidden, use_cache=False)
        p = out.logits[:, -1].float().softmax(-1).cpu()
        res = dict(p_digits=p[:, self.digits].numpy(), p_origin=p[:, self.origin].numpy())
        if not hidden: return res
        span = span.to("cuda")
        if familiarity:  # log p(item token t | <t), text items only
            b, t = span[:, 1:].nonzero(as_tuple=True)
            lp = out.logits[b, t].float().log_softmax(-1).gather(1, enc["input_ids"][b, t + 1][:, None])[:, 0]
            lp_sum = torch.zeros(span.shape[0], device="cuda").index_add_(0, b, lp)
            res["logprob_mean"] = (lp_sum / span[:, 1:].sum(1).clamp(min=1)).cpu().numpy()
        res["n_item_tokens"] = span.sum(1).cpu().numpy()
        H = torch.stack([out.hidden_states[l].to("cuda") for l in self.layers], 1)  # [B,L,T,d]
        m = span[:, None, :, None].to(H.dtype)
        res["last"] = H[:, :, -1].half().cpu().numpy()
        res["mean"] = ((H * m).sum(2) / m.sum(2)).half().cpu().numpy()
        return res


def run(r, name, which, check=False):
    out_r, out_h = RATINGS / which / f"{name}.parquet", HIDDEN / which / f"{name}.npz"
    items = pd.read_parquet(DATA / f"{which}_items.parquet")
    if which == "haiku":
        enc_fn = lambda df: r.encode_haiku(df.haiku.tolist())
    else:
        enc_fn = lambda df: r.encode_images(df.path.tolist(), IMAGE_Q)
    if check:  # rendered prompt + digit mass on a few items
        df = items.iloc[[0, len(items) // 2, len(items) - 1]]
        enc, span, texts = enc_fn(df.iloc[[0]])
        print("=== rendered prompt ===\n" + texts[0] + "\n=== item tokens:", int(span[0].sum()), "| layers", r.layers)
        p = np.concatenate([r.forward(*enc_fn(df.iloc[[i]])[:2])["p_digits"] for i in range(len(df))])
        print("digit mass", p.sum(1).round(3), "| scores", ((p / p.sum(1, keepdims=True)) @ np.arange(1, 10)).round(3))
        return
    recs, last, mean = [], [], []
    for i in tqdm(range(len(items)), desc=f"{name} {which}", mininterval=30):
        df = items.iloc[[i]]
        enc, span, _ = enc_fn(df)
        o = r.forward(enc, span, familiarity=which == "haiku")
        rec = pd.DataFrame(o["p_digits"], columns=[f"p{k}" for k in range(1, 10)]).assign(item_id=df.item_id.values)
        if which == "haiku": rec = rec.assign(logprob_mean=o["logprob_mean"], n_item_tokens=o["n_item_tokens"])
        else:  # human-vs-AI question only where it has an answer key (ACX)
            po = r.forward(*r.encode_images(df.path.tolist(), ORIGIN_Q)[:2], hidden=False)["p_origin"] if df.dataset.iloc[0] == "acx" else np.full((1, 2), np.nan)
            rec = rec.assign(p_human=po[:, 0] / po.sum(1), n_item_tokens=o["n_item_tokens"])
        recs.append(rec); last.append(o["last"]); mean.append(o["mean"])
    rec = pd.concat(recs, ignore_index=True)
    P = rec[[f"p{k}" for k in range(1, 10)]].to_numpy()
    rec["digit_mass"] = P.sum(1); rec["score"] = (P / P.sum(1, keepdims=True)) @ np.arange(1, 10)
    rec.assign(rater=name).to_parquet(out_r)
    np.savez(out_h, item_id=rec.item_id.to_numpy(), layers=np.array(r.layers), last=np.concatenate(last), mean=np.concatenate(mean))
    print(name, which, "digit mass", rec.digit_mass.describe()[["min", "50%"]].round(3).to_dict(), "score", rec.score.describe()[["mean", "std"]].round(3).to_dict())


if __name__ == "__main__":
    ap = argparse.ArgumentParser(); ap.add_argument("raters", nargs="+"); ap.add_argument("--sets", nargs="+", default=["haiku", "images"]); ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    for name in tqdm(a.raters, desc="raters"):
        todo = [w for w in a.sets if a.check or not (RATINGS / w / f"{name}.parquet").exists()]
        if not todo: continue
        r = Rater(name)
        for which in todo:
            (RATINGS / which).mkdir(exist_ok=True); (HIDDEN / which).mkdir(exist_ok=True)
            run(r, name, which, a.check)
        del r; gc.collect(); torch.cuda.empty_cache()
